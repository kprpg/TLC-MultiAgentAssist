import { afterEach, describe, expect, it, vi } from 'vitest'
import { CacheCapacityError, SessionCache } from '../../../apps/shared/session-cache.js'

afterEach(() => vi.useRealTimers())
describe('adaptive memory-only read cache', () => {
  it('distinguishes read-model changes from focus/interest metadata', async () => {
    const cache = new SessionCache()
    const value = cache.value<number>('portfolio')
    await value.read(async () => 1)
    const data = cache.getState().dataRevision
    cache.setActiveKeys(['portfolio']); cache.setActive(true); cache.setActive(false)
    expect(cache.getState().dataRevision).toBe(data)
    value.update(() => 2)
    expect(cache.getState().dataRevision).toBeGreaterThan(data!)
    cache.dispose()
  })
  it('awaits an explicitly invalidated refresh even when its revalidation has already started', async () => {
    const cache = new SessionCache()
    const entry = cache.value<number>('record')
    await entry.read(async () => 1)
    entry.invalidate()
    let release!: (value: number) => void
    const load = vi.fn(() => new Promise<number>((resolve) => { release = resolve }))
    const first = entry.read(load)
    const second = entry.read(load)
    let resolved = false
    void second.then(() => { resolved = true })
    await Promise.resolve()
    expect(resolved).toBe(false)
    release(2)
    expect(await first).toBe(2)
    expect(await second).toBe(2)
    expect(load).toHaveBeenCalledOnce()
    cache.dispose()
  })
  it('returns stable metadata snapshots, deduplicates requests and never refreshes on ordinary cache reads', async () => {
    const cache = new SessionCache()
    const load = vi.fn(async () => ({ value: 1 }))
    const value = cache.value<{ value: number }>('detail:one')
    await Promise.all([value.read(load), value.read(load)])
    const state = cache.getState()
    for (let index = 0; index < 24; index++) await value.read(load)
    expect(load).toHaveBeenCalledOnce()
    expect(cache.getState()).toBe(state)
    expect(cache.getRevision()).toBe(state.revision)
    cache.dispose()
  })
  it('refreshes only loaded visible stale data and retains the previous value while a source refresh is pending', async () => {
    vi.useFakeTimers()
    const cache = new SessionCache({ active: true })
    let release!: (value: { value: number }) => void
    const load = vi.fn(async () => ({ value: 1 }))
    const active = cache.value<{ value: number }>('active')
    const hidden = cache.value<{ value: number }>('hidden')
    await active.read(load); await hidden.read(load)
    cache.setActiveKeys(['active', 'never-loaded'])
    load.mockReturnValue(new Promise((resolve) => { release = resolve }))
    await vi.advanceTimersByTimeAsync(300_000)
    expect(load).toHaveBeenCalledTimes(3)
    expect(active.peek()).toEqual({ value: 1 })
    expect(cache.getState()).toMatchObject({ stale: true, refreshing: true })
    release({ value: 2 })
    await vi.advanceTimersByTimeAsync(1)
    expect(active.peek()).toEqual({ value: 2 })
    expect(hidden.peek()).toEqual({ value: 1 })
    cache.setActive(false)
    await vi.advanceTimersByTimeAsync(600_000)
    expect(load).toHaveBeenCalledTimes(3)
    cache.dispose()
  })
  it('uses longer reference freshness and honors throttling delay with bounded retries', async () => {
    vi.useFakeTimers()
    const cache = new SessionCache({ active: true })
    const reference = cache.value<number[]>('catalog', true)
    const load = vi.fn(async () => [1])
    await reference.read(load)
    cache.setActiveKeys(['catalog'])
    await vi.advanceTimersByTimeAsync(300_000)
    expect(load).toHaveBeenCalledOnce()
    load.mockRejectedValueOnce(Object.assign(new Error('busy'), { status: 429, retryAfterMs: 2000 })).mockResolvedValue([2])
    await vi.advanceTimersByTimeAsync(1_500_000)
    expect(load).toHaveBeenCalledTimes(2)
    await vi.advanceTimersByTimeAsync(1999)
    expect(load).toHaveBeenCalledTimes(2)
    await vi.advanceTimersByTimeAsync(1)
    expect(load).toHaveBeenCalledTimes(3)
    expect(reference.peek()).toEqual([2])
    cache.dispose()
  })
  it('evicts inactive details and rejects oversized complete data rather than truncating it', async () => {
    const cache = new SessionCache({ policy: { maxInactiveEntries: 2, maxSerializedBytes: 1024 } })
    for (const key of ['one', 'two', 'three']) await cache.value<string[]>(key).read(async () => [key])
    expect(cache.has('one')).toBe(false)
    expect(cache.has('three')).toBe(true)
    await expect(cache.value<string>('large').read(async () => 'x'.repeat(2048))).rejects.toBeInstanceOf(CacheCapacityError)
    expect(cache.has('large')).toBe(false)
    cache.dispose()
  })
  it('applies confirmed writes over an older refresh and purges private data on denied reads', async () => {
    const cache = new SessionCache()
    const entry = cache.value<{ value: number }>('record')
    await entry.read(async () => ({ value: 1 }))
    let complete!: (value: { value: number }) => void
    entry.invalidate()
    const pending = entry.read(() => new Promise((resolve) => { complete = resolve }))
    entry.update(() => ({ value: 3 }))
    complete({ value: 2 })
    expect(await pending).toEqual({ value: 3 })
    const denied = cache.value<string[]>('denied')
    await expect(denied.read(async () => { throw Object.assign(new Error('access denied'), { status: 403 }) })).rejects.toThrow('access denied')
    expect(entry.peek()).toBeUndefined()
    cache.dispose()
  })
  it('cancels throttling waits when the source session closes', async () => {
    vi.useFakeTimers()
    const cache = new SessionCache()
    const load = vi.fn(async () => { throw Object.assign(new Error('busy'), { status: 429, retryAfterMs: 60_000 }) })
    const read = cache.value('retry').read(load)
    const rejected = expect(read).rejects.toMatchObject({ name: 'AbortError' })
    await vi.advanceTimersByTimeAsync(1)
    cache.dispose()
    await rejected
    expect(vi.getTimerCount()).toBe(0)
    expect(load).toHaveBeenCalledOnce()
  })
  it('refreshes invalidated active data immediately without discarding the confirmed base', async () => {
    vi.useFakeTimers()
    const cache = new SessionCache({ active: true })
    const entry = cache.value<number>('record')
    const load = vi.fn(async () => 1)
    await entry.read(load)
    cache.setActiveKeys(['record'])
    load.mockResolvedValue(2)
    entry.invalidate()
    expect(entry.peek()).toBe(1)
    await vi.advanceTimersByTimeAsync(10)
    expect(entry.peek()).toBe(2)
    expect(load).toHaveBeenCalledTimes(2)
    cache.dispose()
  })
  it('refreshes the complete loaded parent, not a redundant derived portfolio', async () => {
    vi.useFakeTimers()
    const cache = new SessionCache({ active: true })
    const portfolio = cache.value<number>('portfolio')
    const discovery = cache.value<number>('discovery')
    const loadPortfolio = vi.fn(async () => 1)
    const loadDiscovery = vi.fn(async () => 2)
    discovery.derivedKeys = ['portfolio']
    discovery.onLoad = (value) => portfolio.replaceDerived(value)
    await portfolio.read(loadPortfolio)
    cache.setActiveKeys(['portfolio'])
    await discovery.read(loadDiscovery)
    await vi.advanceTimersByTimeAsync(300_000)
    expect(loadPortfolio).toHaveBeenCalledOnce()
    expect(loadDiscovery).toHaveBeenCalledTimes(2)
    cache.dispose()
  })
  it('validates policy and accounts for bytes added by confirmed updates', async () => {
    expect(() => new SessionCache({ policy: { readRetries: 10 } })).toThrow()
    const cache = new SessionCache({ policy: { maxSerializedBytes: 1024 } })
    const entry = cache.value<string>('record')
    await entry.read(async () => 'original')
    expect(() => entry.update(() => 'x'.repeat(2048))).toThrow(CacheCapacityError)
    expect(entry.peek()).toBe('original')
    cache.dispose()
  })
  it('does not relabel a warm host mirror load as a new source validation', async () => {
    const cache = new SessionCache({ now: () => 200_000 })
    cache.observeSourceState({ generation: 0, revision: 1, fetchedAt: 100_000, validatedAt: 100_000, stale: false, refreshing: false })
    await cache.value('portfolio').read(async () => ['confirmed source data'])
    expect(cache.getState().validatedAt).toBe(100_000)
    const state = cache.getState()
    expect(cache.getState()).toBe(state)
    cache.dispose()
  })
  it('bounds failed and never-loaded entry metadata as well as successful payloads', async () => {
    const cache = new SessionCache({ policy: { maxInactiveEntries: 2 } })
    for (let index = 0; index < 20; index++) {
      await expect(cache.value(`search:${index}`).read(async () => { throw new Error('Rejected source query') })).rejects.toThrow('Rejected source query')
    }
    expect(cache.existing('search:0')).toBeUndefined()
    expect(cache.existing('search:19')).toBeDefined()
    cache.dispose()
  })
  it('does not issue a throttled retry after its pane becomes hidden', async () => {
    vi.useFakeTimers()
    const cache = new SessionCache({ active: true })
    const load = vi.fn(async () => 1)
    await cache.value('portfolio').read(load)
    cache.setActiveKeys(['portfolio'])
    load.mockRejectedValueOnce(Object.assign(new Error('throttled'), { status: 429, retryAfterMs: 60_000 }))
    await vi.advanceTimersByTimeAsync(300_000)
    expect(load).toHaveBeenCalledTimes(2)
    cache.setActive(false)
    await vi.advanceTimersByTimeAsync(60_000)
    expect(load).toHaveBeenCalledTimes(2)
    expect(cache.getState().error).toBeUndefined()
    cache.setActive(true)
    await vi.advanceTimersByTimeAsync(10)
    expect(load).toHaveBeenCalledTimes(3)
    cache.dispose()
  })
  it('keeps the final Retry-After window after exhausting bounded read retries', async () => {
    vi.useFakeTimers()
    const cache = new SessionCache({ active: true, policy: { readRetries: 0 } })
    const load = vi.fn(async () => 1)
    await cache.value('portfolio').read(load)
    cache.setActiveKeys(['portfolio'])
    load.mockRejectedValueOnce(Object.assign(new Error('throttled'), { status: 429, retryAfterMs: 120_000 }))
    await vi.advanceTimersByTimeAsync(300_000)
    await vi.advanceTimersByTimeAsync(119_999)
    expect(load).toHaveBeenCalledTimes(2)
    await vi.advanceTimersByTimeAsync(1)
    expect(load).toHaveBeenCalledTimes(3)
    cache.dispose()
  })
})
