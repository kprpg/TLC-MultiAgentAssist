import { expect, type Page } from '@playwright/test'

export async function openMomentum(page: Page) {
    await page.getByRole('button', { name: 'Dashboards', exact: true }).click()
    await expect(page.getByRole('tab', { name: 'Seller Dashboard', exact: true })).toHaveAttribute('aria-selected', 'true')
    await page.getByRole('tab', { name: 'Momentum & Focus', exact: true }).click()
    await expect(page.getByRole('table', { name: 'Momentum priority queue', exact: true })).toBeVisible()
}

export async function momentumJourney(page: Page) {
    await page.setViewportSize({ width: 1536, height: 960 })
    await openMomentum(page)
    const pane = page.getByRole('region', { name: 'Momentum & Focus', exact: true })
    const queue = pane.getByRole('table', { name: 'Momentum priority queue', exact: true })
    const sections = pane.getByRole('tablist', { name: 'Momentum sections', exact: true })
    const priorities = sections.getByRole('tab', { name: /^Priorities/ })
    const traction = sections.getByRole('tab', { name: /^Traction & signals/ })
    const milestones = sections.getByRole('tab', { name: /^Milestones & deadlines/ })
    const coverage = sections.getByRole('tab', { name: /^Sources & financials/ })
    await expect(sections.getByRole('tab')).toHaveCount(4)
    await expect(priorities).toHaveAttribute('aria-selected', 'true')
    await expect(pane.getByLabel('Customer industry', { exact: true })).toHaveValue('hls')
    await expect(pane).toContainText('SYNTHETIC SAMPLE')
    await expect(queue.getByRole('row').nth(1)).toContainText('Synthetic quiet material blocker')
    const firstRow = await queue.getByRole('row').nth(1).boundingBox()
    const viewportHeight = await page.evaluate(() => window.innerHeight)
    expect(firstRow!.height).toBeLessThanOrEqual(112)
    expect(firstRow!.y + firstRow!.height).toBeLessThanOrEqual(viewportHeight)
    await priorities.press('ArrowRight')
    await expect(traction).toBeFocused()
    await expect(pane.getByRole('img', { name: 'Progress versus signals', exact: true })).toBeVisible()
    await expect(queue).toHaveCount(0)
    await traction.press('End')
    await expect(coverage).toBeFocused()
    await expect(pane.getByRole('table', { name: 'Financial groups table', exact: true })).toBeVisible()
    await coverage.press('Home')
    await expect(priorities).toBeFocused()
    await expect(queue).toBeVisible()
    await pane.getByLabel('Evidence lookback', { exact: true }).selectOption('90')
    await expect(queue).toBeVisible()
    await pane.getByLabel('Focus horizon', { exact: true }).selectOption('month')
    await expect(pane.getByLabel('Evidence lookback', { exact: true })).toHaveValue('90')
    await expect(queue).toBeVisible()
    await pane.getByLabel('Role preset', { exact: true }).selectOption('SE')
    await expect(queue).toBeVisible()
    await queue.getByRole('button', { name: 'Why Synthetic quiet material blocker?', exact: true }).click()
    const detail = page.getByRole('dialog', { name: 'Why this item?', exact: true })
    await expect(detail).toContainText('Recorded deadline')
    await expect(detail).toContainText('not continuous monitoring')
    await expect(detail).toContainText('Solution Engineer')
    await detail.press('Escape')
    await expect(detail).not.toBeVisible()
    await expect(queue.getByRole('button', { name: 'Why Synthetic quiet material blocker?', exact: true })).toBeFocused()

    await traction.click()
    await pane.getByText(/^Insufficient-history records \(/).click()
    await pane.getByRole('button', { name: 'View all insufficient-history records', exact: true }).click()
    await expect(queue).toContainText('Synthetic incomplete coverage')
    await expect(queue).not.toContainText('Synthetic proof decision')
    await expect(priorities).toHaveAttribute('aria-selected', 'true')
    await pane.getByRole('button', { name: 'Clear selection', exact: true }).click()
    await expect(queue).toBeVisible()
    await expect(pane.getByLabel('Customer industry', { exact: true })).toHaveValue('hls')
    await traction.click()
    await pane.getByRole('button', { name: /Select Synthetic harbor:/ }).click()
    await expect(queue).not.toContainText('Synthetic cedar')
    await expect(queue).toContainText('Synthetic harbor')
    await pane.getByRole('button', { name: 'Clear selection', exact: true }).click()
    await expect(queue).toContainText('Synthetic quiet material blocker')
    await milestones.click()
    await pane.getByRole('button', { name: 'Listen & Consult / On Track: 2 milestones', exact: true }).click()
    await expect(queue).not.toContainText('Synthetic quiet material blocker')
    await expect(queue).toContainText('Synthetic proof milestone')
    await pane.getByRole('button', { name: 'Clear selection', exact: true }).click()
    await expect(queue).toBeVisible()

    const total = await pane.getByTestId('momentum-total').textContent()
    await milestones.click()
    const chartTotals = await pane.getByRole('table', { name: 'Deadline distribution table', exact: true }).textContent()
    await priorities.click()
    await pane.getByLabel('Rows per page', { exact: true }).selectOption('2')
    await expect(queue.getByRole('row')).toHaveCount(3)
    await expect(pane.getByTestId('momentum-total')).toHaveText(total!)
    await pane.getByRole('button', { name: 'Next page', exact: true }).click()
    await expect(queue.getByRole('row')).toHaveCount(3)
    await milestones.click()
    expect(await pane.getByRole('table', { name: 'Deadline distribution table', exact: true }).textContent()).toBe(chartTotals)
    await priorities.click()
    await expect(pane.getByLabel('Rows per page', { exact: true })).toHaveValue('2')
    await pane.getByRole('button', { name: 'Refresh and capture history', exact: true }).click()
    await expect(queue).toBeVisible()
    await pane.getByLabel('Portfolio scope', { exact: true }).selectOption('mine')
    await expect(queue).toBeVisible()
    await expect(pane.getByLabel('Role preset', { exact: true })).toHaveValue('SE')
    await page.setViewportSize({ width: 420, height: 900 })
    expect(await pane.evaluate((node) => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
    expect(await pane.getByRole('region', { name: 'Priority queue; scrollable', exact: true }).evaluate((node) => node.scrollWidth > node.clientWidth)).toBe(true)
    await page.getByRole('tab', { name: 'Seller Dashboard', exact: true }).click()
    await page.getByRole('tab', { name: 'Seller Dashboard', exact: true }).press('End')
    await expect(page.getByRole('tab', { name: 'Momentum & Focus', exact: true })).toBeFocused()
    await expect(pane.getByLabel('Role preset', { exact: true })).toHaveValue('SE')
    expect(await page.evaluate(() => Object.keys(localStorage).some((key) => /momentum/i.test(key)))).toBe(false)
}
