test('private work controls pause new work, retain reads and resume only with an explicit action', async ({ page, request }) => {
  await page.goto('/')
  await chooseOpportunity(page, request)
  await page.getByRole('tab', { name: 'Guidance', exact: true }).click()
  try {
    await openUtility(page, 'Activity')
    await page.getByRole('button', { name: 'Pause new work', exact: true }).click({ timeout: 5_000 })
    await expect(page.getByText('Work is paused.', { exact: true })).toBeVisible()
    const blocked = await request.post('/api/teams/operations/workflows.start', { data: {} })
    expect(blocked.status()).toBe(409)
    expect(await blocked.json()).toMatchObject({ error: 'collaboration_paused' })
    await page.getByRole('button', { name: 'Portfolio', exact: true }).click()
    await expect(page.getByLabel('Customer account', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Run guidance', exact: true }).click()
    await expect(page.getByRole('alert').filter({ hasText: 'collaboration paused' })).toBeVisible()
    await openUtility(page, 'Activity')
    await page.getByRole('button', { name: 'Resume work', exact: true }).click()
    await expect(page.getByText('Work is active.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Portfolio', exact: true }).click()
    await page.getByRole('button', { name: 'Run guidance', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Grounded TLC response' })).toBeVisible()
  } finally {
    expect((await request.post('/api/teams/lifecycle', { data: { contractVersion: '1.0', command: 'resume' } })).ok()).toBeTruthy()
  }
})

test('personal workspace uses source data, guided prompts and grounded readable results', async ({ page, request }) => {
  await page.setViewportSize({ width: 1556, height: 900 })
  const failures: string[] = []
  page.on('response', (response) => { if (new URL(response.url()).pathname.startsWith('/api/teams/') && response.status() >= 400) failures.push(`${response.request().method()} ${new URL(response.url()).pathname}: ${response.status()}`) })
  await page.goto('/')
  await expect(page.getByText('Sample data / Offline AI', { exact: true })).toBeVisible()
  await chooseOpportunity(page, request)
  await page.getByRole('tab', { name: 'Guidance', exact: true }).click()
  await page.getByRole('button', { name: 'Run guidance', exact: true }).click()
  const response = page.getByRole('region', { name: 'Grounded TLC response' })
  await expect(response).toBeVisible()
  const exports = response.locator('header').getByRole('group', { name: 'Response exports' })
  await expect(exports).toBeVisible({ timeout: 5000 })
  await expect(exports.getByRole('button', { name: 'Download unsent email draft' })).toBeDisabled()
  const responseBox = await response.boundingBox()
  const exportsBox = await exports.boundingBox()
  expect(Math.abs(exportsBox!.x + exportsBox!.width - responseBox!.x - responseBox!.width)).toBeLessThanOrEqual(2)
  await expect(page.getByText('Evidence and source health', { exact: true })).toBeVisible()
  const [wordDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export Word', exact: true }).click()])
  expect(wordDownload.suggestedFilename()).toBe('TLC-response.docx')
  const documentPath = await wordDownload.path()
  if (!documentPath) throw new Error('The actual Word download was not saved.')
  expect((await JSZip.loadAsync(await readFile(documentPath))).file('word/document.xml')).not.toBeNull()
  await page.getByLabel('Email draft recipients').fill('reviewer@example.com')
  const [email] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download unsent email draft' }).click()])
  expect(email.suggestedFilename()).toBe('TLC-reviewed-draft.eml')
  const emailPath = await email.path()
  if (!emailPath) throw new Error('The actual email draft was not saved.')
  expect(await readFile(emailPath, 'utf8')).toContain('X-Unsent: 1')
  expect(failures).toEqual([])
  expect(await page.evaluate(() => Object.keys(localStorage).filter((key) => /token|msal/i.test(key)))).toEqual([])
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await expect(exports).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
})

test('response exports report failures, validate recipients and permit a deliberate retry', async ({ page, request }) => {
  await page.goto('/')
  await chooseOpportunity(page, request)
  await page.getByRole('tab', { name: 'Guidance', exact: true }).click()
  await page.getByRole('button', { name: 'Run guidance', exact: true }).click()
  const exports = page.getByRole('region', { name: 'Grounded TLC response' }).getByRole('group', { name: 'Response exports' })
  await page.route('**/documents/export', (route) => route.fulfill({
    status: 503, contentType: 'application/json',
    body: JSON.stringify({ error: 'export_temporarily_unavailable', correlationId: 'sanitized-export-reference' })
  }))
  await exports.getByRole('button', { name: 'Export Word', exact: true }).click()
  await expect(exports.getByRole('alert')).toContainText('export temporarily unavailable')
  await expect(exports.getByRole('alert')).toContainText('sanitized-export-reference')
  await expect(exports.getByRole('button', { name: 'Export Word', exact: true })).toBeEnabled()
  await page.unroute('**/documents/export')
  const [wordDownload] = await Promise.all([page.waitForEvent('download'), exports.getByRole('button', { name: 'Export Word', exact: true }).click()])
  expect(wordDownload.suggestedFilename()).toBe('TLC-response.docx')
  let emailRequests = 0
  page.on('request', (entry) => { if (entry.url().endsWith('/documents/email')) emailRequests++ })
  await exports.getByLabel('Email draft recipients', { exact: true }).fill('not-an-email')
  await exports.getByRole('button', { name: 'Download unsent email draft', exact: true }).click()
  await expect(exports.getByRole('alert')).toContainText('valid email addresses')
  expect(emailRequests).toBe(0)
})

test('opportunity comments are visible and editable through review in the Opportunities pane', async ({ page, request }) => {
  await page.goto('/')
  const { opportunity } = await chooseOpportunity(page, request)
  const before = await post(request, 'getOpportunityContext', { opportunityId: opportunity.id })
  await page.getByRole('button', { name: 'Hide opportunity details panel', exact: true }).click()
  await page.getByRole('button', { name: 'Hide Next Best Actions panel', exact: true }).click()
  const list = page.getByRole('region', { name: 'Opportunity list', exact: true })
  await expect(list.getByRole('columnheader', { name: 'Comments', exact: true })).toBeVisible({ timeout: 5000 })
  const row = list.getByRole('row').filter({ hasText: opportunity.name })
  await expect(row.getByRole('cell').last()).toContainText(before.opportunity.comments || 'No comments recorded.')
  await row.getByText('Opportunity Comments', { exact: true }).click()
  await row.getByLabel(`Comments for ${opportunity.name}`, { exact: true }).fill('Opportunity pane reviewed comment')
  await row.getByRole('button', { name: 'Review opportunity update', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Review exact changes' })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel review', exact: true }).click()
  expect(await post(request, 'getOpportunityContext', { opportunityId: opportunity.id })).toEqual(before)
  await row.getByRole('button', { name: 'Review opportunity update', exact: true }).click()
  await page.getByLabel('Review reason', { exact: true }).fill('Verified the opportunity comment and scope')
  await page.getByRole('button', { name: 'Confirm selected changes', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Review exact changes' })).not.toBeVisible()
  await expect(row.locator('.opportunity-comments-preview')).toHaveText('Opportunity pane reviewed comment')
  expect((await post(request, 'getOpportunityContext', { opportunityId: opportunity.id })).opportunity.comments).toBe('Opportunity pane reviewed comment')
})

